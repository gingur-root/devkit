const CLI = fileURLToPath(new URL('../devkit.mjs', import.meta.url));
const HEADER =
  "# Memory\n\nGenerated by `devkit memory reindex` from each folder's INDEX.md. Do not edit.\n";
const MEMORY = `${HEADER}\n## devkit\n\n- [policy](devkit/policy.md): A policy\n`;

function entry(overrides: Record<string, unknown> = {}): string {
  return `---\n${stringify({
    name: 'policy',
    description: 'A policy',
    type: 'fact',
    date: '2026-10-19',
    source: 'gingur-root/devkit#257',
    supersedes: null,
    evidence: [{ at: 'gingur-root/devkit:AGENTS.md', quote: 'Simple first.' }],
    ...overrides,
  })}---\n\nThe policy.\n`;
}

function put(dir: string, file: string, text: string): void {
  mkdirSync(dirname(join(dir, file)), { recursive: true });
  writeFileSync(join(dir, file), text);
}

function fixture(): string {
  const dir = mkdtempSync(join(tmpdir(), 'devkit-memory-'));
  onTestFinished(() => rmSync(dir, { recursive: true, force: true }));
  put(dir, 'devkit/INDEX.md', '# Policies\n\n- [policy](policy.md): A policy\n');
  put(dir, 'devkit/policy.md', entry());
  put(dir, 'MEMORY.md', MEMORY);
  return dir;
}

function cli(dir: string, ...args: string[]) {
  return spawnSync(process.execPath, [CLI, 'memory', ...args, '--dir', dir], {
    encoding: 'utf8',
  });
}

