for (const [name, edit, file, reason] of structureCases) {
  test(`structure: ${name} is reported by the API and CLI`, async () => {
    const dir = fixture();
    edit(dir);
    assert.deepEqual(await check(dir, { offline: true }), [{ file, reason }]);
    const result = cli(dir, 'check', '--offline');
    assert.equal(result.status, 1, result.stderr);
    assert.equal(result.stdout, `${file}: ${reason}\n`);
  });
}

