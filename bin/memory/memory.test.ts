test('reindex is byte-exact, ordered, deterministic, and detects index edits', async () => {
  const dir = fixture();
  put(dir, 'z-last/INDEX.md', '- [z](z.md): Last\n');
  put(dir, 'z-last/z.md', entry({ name: 'z', type: 'decision', evidence: [] }));
  put(dir, '_org/INDEX.md', '# Org\nignore this\n- [b](b.md): Second\n- [a](a.md): First\n');
  for (const name of ['a', 'b'])
    put(dir, `_org/${name}.md`, entry({ name, type: 'decision', evidence: [] }));
  put(dir, 'ignored.md', 'A root file');
  mkdirSync(join(dir, 'empty'));
  const expected = `${HEADER}\n## _org\n\n- [b](_org/b.md): Second\n- [a](_org/a.md): First\n\n## devkit\n\n- [policy](devkit/policy.md): A policy\n\n## z-last\n\n- [z](z-last/z.md): Last\n`;
  assert.equal(render(dir), expected);
  for (let i = 0; i < 2; i++) {
    const result = cli(dir, 'reindex');
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout, '');
    assert.equal(readFileSync(join(dir, 'MEMORY.md'), 'utf8'), expected);
  }
  assert.deepEqual(await check(dir, { offline: true }), []);
  const clean = cli(dir, 'check', '--offline');
  assert.equal(clean.status, 0, clean.stderr);
  assert.equal(clean.stdout, '');
  put(dir, 'devkit/INDEX.md', '- [policy](policy.md): Edited description\n');
  assert.deepEqual(await check(dir, { offline: true }), [
    { file: 'MEMORY.md', reason: 'out of sync' },
  ]);
});

