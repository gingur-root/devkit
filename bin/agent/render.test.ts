function memoryFixture() {
  const files = new Map([
    ['_org/INDEX.md', '# Org\n\n- [A](a.md) — Org fact\n'],
    ['_org/a.md', 'Org evidence\n'],
    ['r/INDEX.md', '# Repo\n\n- [B](b.md) — Repo fact\n'],
    ['r/b.md', 'Repo evidence\n'],
    ['infra/INDEX.md', '# Infra\n\n- [C](c.md) — Infra fact\n'],
    ['infra/c.md', 'Infra evidence\n'],
  ]);
  const failures = new Map<string, number>();
  const requests: { url: URL; authorization: string | null }[] = [];
  const prefix = '/repos/gingur-root/pipeline';
  vi.stubEnv('GH_TOKEN', 'target-token');
  vi.stubEnv('MEMORY_TOKEN', 'memory-token');
  vi.stubGlobal('fetch', async (url: string, init: RequestInit) => {
    const request = new URL(url);
    const path = request.pathname;
    if (path.startsWith(`${prefix}/`)) {
      requests.push({
        url: request,
        authorization: new Headers(init.headers).get('authorization'),
      });
      const status = failures.get(path.slice(prefix.length));
      if (status) return new Response('{"message":"fixture memory failure"}', { status });
      if (path === `${prefix}/commits/main`) return Response.json({ sha: 'mem1' });
      if (path === `${prefix}/contents/memory`)
        return Response.json(['_org', 'r', 'infra'].map((name) => ({ name, type: 'dir' })));
      const relative = path.slice(`${prefix}/contents/memory/`.length);
      if (files.has(relative))
        return Response.json({ content: Buffer.from(files.get(relative)!).toString('base64') });
      const entries = [...files.keys()]
        .filter((file) => file.startsWith(`${relative}/`))
        .map((file) => ({ name: file.slice(relative.length + 1), type: 'file' }));
      if (entries.length)
        return Response.json([
          ...entries,
          { name: 'ignored.json', type: 'file' },
          { name: 'nested.md', type: 'dir' },
        ]);
      return new Response('{"message":"Not Found"}', { status: 404 });
    }
    assert.equal(new Headers(init.headers).get('authorization'), 'Bearer target-token');
    if (path.includes('/contents/') || path.endsWith('/parent'))
      return new Response('{}', { status: 404 });
    const routes: Record<string, unknown> = {
      '/repos/o/r/issues/1': {
        number: 1,
        title: 'Title',
        body: 'Body',
        user: { id: OPERATOR_ID },
        labels: [],
      },
      '/repos/o/r/issues/1/comments': [comment()],
    };
    return Response.json(routes[path] ?? []);
  });
  return { files, failures, requests };
}

test('every role renders only org and repo Markdown at one memory SHA with the read token', async () => {
  const out = mkdtempSync(join(tmpdir(), 'render-memory-'));
  const fixture = memoryFixture();
  const expectedIndex =
    "# Memory\n\nGenerated by `devkit memory reindex` from each folder's INDEX.md. Do not edit.\n\n## _org\n\n- [A](_org/a.md) — Org fact\n\n## r\n\n- [B](r/b.md) — Repo fact\n";
  try {
    for (const role of [
      'plan',
      'build',
      'review',
      'repair',
      'replan',
      'verify',
      'retro',
      'hello',
    ] as const) {
      fixture.requests.length = 0;
      // A retry must remove a previously rendered repo's slice too.
      mkdirSync(join(out, 'memory/infra'), { recursive: true });
      writeFileSync(join(out, 'memory/infra/stale.md'), 'stale');
      const job = await render({
        repo: 'o/r',
        issue: 1,
        role,
        source: 'abc',
        appId: APP,
        dispatcher: OPERATOR_ID,
        out,
      });
      assert.equal(job.memory, 'mem1');
      const dir = join(out, 'memory');
      assert.deepEqual(readdirSync(dir, { recursive: true }).sort(), [
        'INDEX.md',
        '_org',
        '_org/INDEX.md',
        '_org/a.md',
        'r',
        'r/INDEX.md',
        'r/b.md',
      ]);
      for (const [file, content] of fixture.files) {
        if (!file.startsWith('infra/'))
          assert.equal(readFileSync(join(dir, file), 'utf8'), content);
      }
      assert.equal(readFileSync(join(dir, 'INDEX.md'), 'utf8'), expectedIndex);
      assert.equal(memoryIndex(dir), expectedIndex);
      const json = JSON.parse(readFileSync(join(out, 'job.json'), 'utf8'));
      assert.equal(Job.parse(json).memory, 'mem1');
      delete json.memory;
      assert.equal(Job.parse(json).memory, null);
      assert.deepEqual(
        fixture.requests.map(({ url }) => url.pathname),
        [
          '/repos/gingur-root/pipeline/commits/main',
          '/repos/gingur-root/pipeline/contents/memory',
          '/repos/gingur-root/pipeline/contents/memory/_org',
          '/repos/gingur-root/pipeline/contents/memory/_org/INDEX.md',
          '/repos/gingur-root/pipeline/contents/memory/_org/a.md',
          '/repos/gingur-root/pipeline/contents/memory/r',
          '/repos/gingur-root/pipeline/contents/memory/r/INDEX.md',
          '/repos/gingur-root/pipeline/contents/memory/r/b.md',
        ],
      );
      for (const { url, authorization } of fixture.requests) {
        assert.equal(authorization, 'Bearer memory-token');
        if (url.pathname.includes('/contents/')) assert.equal(url.searchParams.get('ref'), 'mem1');
      }
    }
  } finally {
    rmSync(out, { recursive: true, force: true });
    vi.unstubAllGlobals();
    vi.unstubAllEnvs();
  }
});

